"""Finds the `unsafe` sites in the code that ships, for scripts/ledger-check.

What it does not understand ships: a `cfg` it cannot evaluate counts as possibly true, and a
module, `include!` or `#[path]` it cannot follow is a problem that fails the check.

The code that ships is what the allocator and preload crates compile in a build that serves a
program: the module tree from each crate's `src/lib.rs`, without what a `#[cfg(...)]` keeps
out of every such build. Such a build has some of the optional features, either C library,
and debug assertions on or off; it never has `test`, Kani, Miri or the features `sim` and
`internals`, which only the tests, the test kit, the fuzz targets and the benchmarks enable.
Two kinds of file are exempt: the scaffolding in `SCAFFOLDING` (the twins, which serve tests
and the simulated heap but compile everywhere), and the routines the Lean emitter wrote under
`front/generated/`, which carry their proofs and which `generated-check` keeps unedited.

A site is an `unsafe` block, `unsafe fn`, `unsafe impl`, `unsafe trait`, `extern` block (with
or without `unsafe`), `#[unsafe(...)]` attribute, also under `cfg_attr`, or any other use of
the keyword, such as one passed to a macro. Its justification is the run of comment lines
directly above the line the `unsafe` is on (across attribute lines, not across a blank line or
a line of code), unless a block opens or a statement ends before the `unsafe` on its line,
and the comments after it on that line. A
contract (`unsafe fn`, `unsafe trait`) needs a `# Safety` section there; a method of a trait's
implementation has the trait's and is not a site. Every other site must cite a ledger entry,
or name a Kani harness as ``Kani: `harness_name` `` that a module of the crate declares.

Two more rules, over every module the shipping crates declare whatever its cfg: no
`asm!`, `naked_asm!` or `global_asm!` but in the Lean routines and the one system-call
instruction (`SYSTEM_CALL`); and no shipping crate's manifest turns on the allocator's `sim`
or `internals`.

The scan is a small lexer and a token walk, not a Rust parser. `self_test()` runs it over
small cases of each thing above; the gate runs it with the check.

Usage: python3 scripts/unsafe_sites.py   (runs the self-test)
"""

from __future__ import annotations

import itertools
import pathlib
import re
import sys
import tempfile
import tomllib
from dataclasses import dataclass

SHIPPING_CRATES = ("cralloc", "cralloc-preload", "cralloc-tokio")
# The file of the one system-call instruction, the only hand-written assembly (CLAUDE.md).
SYSTEM_CALL = "crates/cralloc/src/os/linux/syscall.rs"
ASSEMBLY_MACROS = ("asm", "naked_asm", "global_asm")
# Scaffolding that compiles in every build but serves only tests, relative to the root.
SCAFFOLDING = {"crates/cralloc/src/front/twin.rs"}
LEAN_DIR = "crates/cralloc/src/front/generated"
LEAN_GENERATED = "// @generated by lean/Emit.lean."

ID = re.compile(r"(?<![A-Za-z0-9-])[A-Z]+(?:-[A-Z]+)*-[0-9]{2}(?![0-9])")
SAFETY_SECTION = re.compile(r"^\s*//[/!]\s*# Safety\s*$", re.M)
KANI_NAMED = re.compile(r"Kani:\s*`(?:[A-Za-z0-9_]+::)*([A-Za-z0-9_]+)`")

# Sites that state a contract rather than discharge one: they need a `# Safety` section.
CONTRACTS = ("fn", "trait")

# Features a build that serves a program may have, and features it never has.
OPTIONAL_FEATURES = ("background", "allocator-api", "executable", "c-abi")
NEVER_FEATURES = ("sim", "internals")
# Flags that are never set in such a build.
FALSE_FLAGS = {"test", "miri", "kani", "doc", "doctest", "false"}
FIXED = {
    "target_os": "linux",
    "target_arch": "x86_64",
    "target_family": "unix",
    "target_pointer_width": "64",
    "target_endian": "little",
}


@dataclass
class Token:
    kind: str  # ident, punct, str, char, lifetime, num, comment
    text: str
    line: int

    @property
    def end_line(self) -> int:
        return self.line + self.text.count("\n")


def lex(text: str) -> list[Token]:
    tokens: list[Token] = []
    i, line, n = 0, 1, len(text)

    def advance_to(j: int) -> None:
        nonlocal i, line
        line += text.count("\n", i, j)
        i = j

    while i < n:
        c = text[i]
        if c.isspace():
            advance_to(i + 1)
            continue
        start_line = line
        if text.startswith("//", i):
            j = text.find("\n", i)
            j = n if j < 0 else j
            tokens.append(Token("comment", text[i:j], start_line))
            advance_to(j)
            continue
        if text.startswith("/*", i):
            depth, j = 1, i + 2
            while j < n and depth:
                if text.startswith("/*", j):
                    depth, j = depth + 1, j + 2
                elif text.startswith("*/", j):
                    depth, j = depth - 1, j + 2
                else:
                    j += 1
            tokens.append(Token("comment", text[i:j], start_line))
            advance_to(j)
            continue
        if c.isalpha() or c == "_":
            j = i
            while j < n and (text[j].isalnum() or text[j] == "_"):
                j += 1
            word = text[i:j]
            if word == "r" and text.startswith("#", j) and j + 1 < n and (
                text[j + 1].isalpha() or text[j + 1] == "_"
            ):
                # A raw identifier, `r#unsafe`: an identifier, never the keyword.
                k = j + 1
                while k < n and (text[k].isalnum() or text[k] == "_"):
                    k += 1
                tokens.append(Token("ident", text[i:k], start_line))
                advance_to(k)
                continue
            if word in ("r", "br", "cr") and j < n and text[j] in "#\"":
                hashes = 0
                while j + hashes < n and text[j + hashes] == "#":
                    hashes += 1
                if j + hashes < n and text[j + hashes] == '"':
                    end = text.find('"' + "#" * hashes, j + hashes + 1)
                    end = n if end < 0 else end + 1 + hashes
                    tokens.append(Token("str", text[i:end], start_line))
                    advance_to(end)
                    continue
            if word in ("b", "c") and j < n and text[j] in "\"'":
                end = skip_quoted(text, j)
                tokens.append(Token("str", text[i:end], start_line))
                advance_to(end)
                continue
            tokens.append(Token("ident", word, start_line))
            advance_to(j)
            continue
        if c == '"':
            end = skip_quoted(text, i)
            tokens.append(Token("str", text[i:end], start_line))
            advance_to(end)
            continue
        if c == "'":
            if i + 1 < n and text[i + 1] == "\\":
                end = skip_quoted(text, i)
                tokens.append(Token("char", text[i:end], start_line))
                advance_to(end)
                continue
            if i + 2 < n and text[i + 2] == "'":
                tokens.append(Token("char", text[i : i + 3], start_line))
                advance_to(i + 3)
                continue
            j = i + 1
            while j < n and (text[j].isalnum() or text[j] == "_"):
                j += 1
            tokens.append(Token("lifetime", text[i:j], start_line))
            advance_to(j)
            continue
        if c.isdigit():
            j = i
            while j < n and (text[j].isalnum() or text[j] == "_"):
                j += 1
            tokens.append(Token("num", text[i:j], start_line))
            advance_to(j)
            continue
        tokens.append(Token("punct", c, start_line))
        advance_to(i + 1)
    return tokens


def skip_quoted(text: str, i: int) -> int:
    """The index just past the quoted literal that starts at `text[i]`."""
    quote, j, n = text[i], i + 1, len(text)
    while j < n and text[j] != quote:
        j += 2 if text[j] == "\\" else 1
    return j + 1


def shipping_configs() -> list[dict]:
    """Every combination of what varies between builds that serve a program."""
    configs = []
    choices = [("gnu", "musl"), (False, True)] + [(False, True)] * len(OPTIONAL_FEATURES)
    for env, debug, *flags in itertools.product(*choices):
        features = {name for name, on in zip(OPTIONAL_FEATURES, flags) if on}
        configs.append({"target_env": env, "debug_assertions": debug, "features": features})
    return configs


CONFIGS = shipping_configs()


def split_args(tokens: list[Token]) -> list[list[Token]]:
    """The comma-separated arguments of a parenthesized list's inside."""
    args, current, depth = [], [], 0
    for t in tokens:
        if t.kind == "punct" and t.text in "([{":
            depth += 1
        elif t.kind == "punct" and t.text in ")]}":
            depth -= 1
        if depth == 0 and t.kind == "punct" and t.text == ",":
            args.append(current)
            current = []
        else:
            current.append(t)
    if current:
        args.append(current)
    return args


def evaluate(pred: list[Token], config: dict) -> bool | None:
    """A cfg predicate under `config`: true, false, or `None` for one it does not know."""
    if not pred:
        return None
    head = pred[0]
    if head.kind == "ident" and len(pred) > 1 and pred[1].text == "(":
        results = [evaluate(arg, config) for arg in split_args(pred[2:-1])]
        if head.text == "all":
            return False if False in results else (None if None in results else True)
        if head.text == "any":
            return True if True in results else (None if None in results else False)
        if head.text == "not" and len(results) == 1:
            return None if results[0] is None else not results[0]
        return None
    if head.kind == "ident" and len(pred) == 3 and pred[1].text == "=" and pred[2].kind == "str":
        value = pred[2].text.strip('"')
        if head.text == "feature":
            if value in OPTIONAL_FEATURES:
                return value in config["features"]
            return False if value in NEVER_FEATURES else None
        if head.text == "target_env":
            return value == config["target_env"]
        if head.text in FIXED:
            return FIXED[head.text] == value
        return None
    if head.kind == "ident" and len(pred) == 1:
        if head.text in FALSE_FLAGS:
            return False
        if head.text == "debug_assertions":
            return config["debug_assertions"]
        if head.text in ("unix", "true"):
            return True
        return None
    return None


def ships(pred: list[Token]) -> bool:
    """Whether code under the predicate may be in some build that serves a program."""
    return any(evaluate(pred, config) is not False for config in CONFIGS)


def matching(tokens: list[Token], i: int) -> int:
    """The index of the bracket that closes the one at `tokens[i]`."""
    depth = 0
    for j in range(i, len(tokens)):
        t = tokens[j]
        if t.kind == "punct" and t.text in "([{":
            depth += 1
        elif t.kind == "punct" and t.text in ")]}":
            depth -= 1
            if depth == 0:
                return j
    return len(tokens) - 1


def opening(tokens: list[Token], close: int) -> int:
    """The index of the bracket that opens the one at `tokens[close]`."""
    depth = 0
    for j in range(close, -1, -1):
        t = tokens[j]
        if t.kind == "punct" and t.text in ")]}":
            depth += 1
        elif t.kind == "punct" and t.text in "([{":
            depth -= 1
            if depth == 0:
                return j
    return 0


ITEM_WORDS = {
    "fn", "impl", "struct", "enum", "union", "trait", "mod", "macro_rules", "extern", "unsafe",
    "async", "const", "static", "use", "type", "let",
}
SEMICOLON_ITEMS = {"use", "static", "const", "type", "let"}


def item_end(tokens: list[Token], i: int) -> int:
    """The index of the last token of the item, field, arm or statement at `tokens[i]`."""
    j = i
    while j < len(tokens) and tokens[j].kind == "comment":
        j += 1
    k = j
    if k < len(tokens) and tokens[k].text == "pub":
        k += 1
        if k < len(tokens) and tokens[k].text == "(":
            k = matching(tokens, k) + 1
    first = tokens[k].text if k < len(tokens) else ""
    # `const fn`, `const unsafe fn`, `const extern "C" fn`, `const async fn`: a function.
    if first == "const" and k + 1 < len(tokens) and tokens[k + 1].text in (
        "fn", "unsafe", "extern", "async"
    ):
        first = "fn"
    item = first in ITEM_WORDS
    depth = 0
    for m in range(j, len(tokens)):
        t = tokens[m]
        if t.kind != "punct":
            continue
        if t.text in "([{":
            depth += 1
        elif t.text in ")]}":
            depth -= 1
            if depth < 0:
                return m - 1
            if depth == 0 and t.text == "}" and first not in SEMICOLON_ITEMS:
                nxt = tokens[m + 1] if m + 1 < len(tokens) else None
                if nxt is not None and nxt.kind == "punct" and nxt.text in ";,":
                    return m + 1
                return m
        elif depth == 0 and (t.text == ";" or (t.text == "," and not item)):
            return m
    return len(tokens) - 1


def in_trait_impl(tokens: list[Token], i: int) -> bool:
    """Whether `tokens[i]` is directly inside an `impl Trait for Type { ... }` block. The
    `for` of a trait impl comes before any `where` and is not a `for<'a>` binder."""
    depth = 0
    for j in range(i - 1, -1, -1):
        t = tokens[j]
        if t.kind != "punct":
            continue
        if t.text in ")]}":
            depth += 1
        elif t.text in "([{":
            if depth:
                depth -= 1
                continue
            if t.text != "{":
                return False
            start = j - 1
            while start >= 0 and not (tokens[start].kind == "punct" and tokens[start].text in ";{}"):
                start -= 1
            header = tokens[start + 1 : j]
            if not any(h.text == "impl" for h in header):
                return False
            for n, h in enumerate(header):
                if h.text == "where":
                    return False
                nxt = header[n + 1] if n + 1 < len(header) else None
                if h.kind == "ident" and h.text == "for" and not (nxt and nxt.text == "<"):
                    return True
            return False
    return False


@dataclass
class Site:
    path: pathlib.Path
    line: int
    kind: str
    justified: str  # the comments that justify it
    lean: bool = False  # in a routine the Lean emitter wrote from a proved artifact
    problem: bool = False  # something the scan could not follow, which fails the check


class Walker:
    def __init__(self, root: pathlib.Path, gated: bool = True):
        self.root = root
        # With `gated` false, every module counts, whatever its cfg: what the crate declares.
        self.gated = gated
        self.sites: list[Site] = []
        self.files: list[pathlib.Path] = []
        self.lean = False
        # Every `asm!`, `naked_asm!` and `global_asm!`: (file, line, macro).
        self.assembly: list[tuple[pathlib.Path, int, str]] = []

    def problem(self, path: pathlib.Path, line: int, what: str) -> None:
        self.sites.append(Site(path, line, what, "", problem=True))

    def walk_file(self, path: pathlib.Path, module_dir: pathlib.Path, line_of_mod: tuple | None = None) -> None:
        if not path.is_file():
            if line_of_mod is not None:
                self.problem(*line_of_mod, f"module file not found: {path.name}")
            return
        relative = path.relative_to(self.root).as_posix()
        if self.gated and relative in SCAFFOLDING:
            return
        # A module declared twice under exclusive cfgs (`pub mod os` with a feature, `mod os`
        # without) is one file, walked once.
        if path in self.files:
            return
        self.files.append(path)
        text = path.read_text()
        tokens = lex(text)
        lean = relative.startswith(LEAN_DIR + "/") and text.startswith(LEAN_GENERATED)
        outer, self.lean = self.lean, lean
        self.walk(tokens, 0, len(tokens), path, module_dir)
        self.lean = outer

    def ships(self, pred: list[Token]) -> bool:
        return not self.gated or ships(pred)

    def walk(self, tokens, start, end, path, module_dir) -> None:
        i = start
        pending_path = None
        while i < end:
            t = tokens[i]
            if t.kind == "punct" and t.text == "#" and i + 1 < end and tokens[i + 1].text in "[!":
                inner = tokens[i + 1].text == "!"
                open_at = i + 2 if inner else i + 1
                close = matching(tokens, open_at)
                body = tokens[open_at + 1 : close]
                attrs = [body]
                if body and body[0].text == "cfg_attr" and len(body) > 1 and body[1].text == "(":
                    args = split_args(body[2:-1])
                    attrs = args[1:] if args and self.ships(args[0]) else []
                skip = False
                for attr in attrs:
                    if len(attr) >= 3 and attr[0].text == "cfg" and attr[1].text == "(":
                        if not self.ships(attr[2:-1]):
                            skip = True
                    if len(attr) == 3 and attr[0].text == "path" and attr[1].text == "=":
                        pending_path = attr[2].text.strip('"')
                    if attr and attr[0].text == "unsafe" and len(attr) > 1 and attr[1].text == "(":
                        self.site(tokens, i, path, "attribute")
                if skip:
                    if inner:
                        return
                    after = close + 1
                    # Further attributes belong to the same item.
                    while after < end and tokens[after].text == "#":
                        after = matching(tokens, after + 1) + 1
                    i = item_end(tokens, after) + 1
                    pending_path = None
                    continue
                i = close + 1
                continue
            if t.kind == "ident" and t.text == "mod" and i + 1 < end:
                nxt = tokens[i + 1]
                if nxt.kind == "punct" and nxt.text == "$":
                    self.problem(path, t.line, "a module declared by a macro")
                elif nxt.kind == "ident" and i + 2 < end:
                    after = tokens[i + 2]
                    if after.text == ";":
                        self.declared(path, module_dir, nxt.text, pending_path, t.line)
                        pending_path = None
                        i += 3
                        continue
                    if after.text == "{":
                        close = matching(tokens, i + 2)
                        self.walk(tokens, i + 3, close, path, module_dir / nxt.text)
                        pending_path = None
                        i = close + 1
                        continue
            if (
                t.kind == "ident"
                and t.text in ("include", "include_str", "include_bytes")
                and i + 2 < end
                and tokens[i + 1].text == "!"
            ):
                if t.text == "include":
                    self.included(tokens, i, path, module_dir)
            if (
                t.kind == "ident"
                and t.text in ASSEMBLY_MACROS
                and i + 1 < end
                and tokens[i + 1].text == "!"
            ):
                self.assembly.append((path, t.line, t.text))
            if t.kind == "ident" and t.text == "unsafe":
                kind = self.kind(tokens, i)
                # A method of a trait's implementation states no contract of its own: it has
                # the trait's, which is documented where the trait is.
                if kind and not (kind == "fn" and in_trait_impl(tokens, i)):
                    self.site(tokens, i, path, kind)
            if t.kind == "ident" and t.text == "extern" and not (i > 0 and tokens[i - 1].text == "unsafe"):
                j = i + 1
                if j < end and tokens[j].kind == "str":
                    j += 1
                if j < end and tokens[j].text == "{":
                    self.site(tokens, i, path, "extern block")
            if t.kind == "punct" and t.text in ";{}":
                pending_path = None
            i += 1

    def included(self, tokens, i, path, module_dir) -> None:
        open_at = i + 2
        close = matching(tokens, open_at)
        inside = tokens[open_at + 1 : close]
        if len(inside) == 1 and inside[0].kind == "str" and not inside[0].text.startswith(("r", "b")):
            target = path.parent / inside[0].text.strip('"')
            if target.is_file():
                text = target.read_text()
                self.files.append(target)
                self.walk(lex(text), 0, len(lex(text)), target, module_dir)
                return
        self.problem(path, tokens[i].line, "an include! the scan cannot follow")

    def declared(self, path, module_dir, name, explicit, line) -> None:
        if explicit is not None:
            # `#[path]` is relative to the declaring file's directory.
            target = path.parent / explicit
            child_dir = target.parent / target.stem
        else:
            target = module_dir / f"{name}.rs"
            child_dir = module_dir / name
            if not target.exists():
                target = module_dir / name / "mod.rs"
        if target.name == "mod.rs":
            child_dir = target.parent
        self.walk_file(target, child_dir, (path, line))

    @staticmethod
    def kind(tokens, i) -> str | None:
        nxt = tokens[i + 1] if i + 1 < len(tokens) else None
        if nxt is None:
            return None
        if nxt.text == "{":
            return "block"
        if nxt.text in ("impl", "trait"):
            return nxt.text
        j = i + 1
        if nxt.text == "extern":
            j += 1
            if j < len(tokens) and tokens[j].kind == "str":
                j += 1
            if j < len(tokens) and tokens[j].text == "{":
                return "extern block"
        if j < len(tokens) and tokens[j].text == "fn":
            # `unsafe fn(...)` is a function pointer type, not a function, and not a site.
            if j + 1 < len(tokens) and tokens[j + 1].kind == "ident":
                return "fn"
            return None
        # Anything else, such as the keyword passed to a macro as a token (`m!(unsafe, p)`),
        # is a use the scan does not understand, so it is a site that must be justified.
        return "keyword"

    def site(self, tokens, i, path, kind) -> None:
        line = tokens[i].line
        if self.lean:
            self.sites.append(Site(path, line, kind, "", lean=True))
            return
        # The comments after the site on its own line.
        comments = [
            t.text for t in tokens[i + 1 :] if t.kind == "comment" and t.line == line
        ]
        # The run of comment lines directly above the site's line, across attributes.
        first = i
        while first > 0 and tokens[first - 1].end_line == line:
            first -= 1
        # A block opened or a statement ended on the line before the site makes the site
        # part of something the comments above do not describe (`fn f() { unsafe { .. } }`
        # under the function's documentation, `g(); unsafe { .. }`).
        depth = 0
        for t in tokens[first:i]:
            if t.kind == "punct" and t.text in "{(":
                depth += 1
            elif t.kind == "punct" and t.text in "})":
                depth -= 1
            elif t.kind == "punct" and t.text == ";" and depth <= 0:
                depth = 1
                break
        if depth > 0 and any(t.kind == "punct" and t.text in "{;" for t in tokens[first:i]):
            self.sites.append(Site(path, line, kind, "\n".join(comments)))
            return
        j, above = first - 1, line
        while j >= 0:
            t = tokens[j]
            if t.end_line < above - 1:
                break  # a blank line
            if t.kind == "comment":
                # Only a comment that starts its line; a trailing one belongs to the code
                # before it.
                if j > 0 and tokens[j - 1].end_line == t.line:
                    break
                comments.append(t.text)
                above, j = t.line, j - 1
                continue
            if t.kind == "punct" and t.text == "]":
                start = opening(tokens, j)
                k = start - 1
                if k >= 0 and tokens[k].text == "!":
                    k -= 1
                if k >= 0 and tokens[k].text == "#" and not (k > 0 and tokens[k - 1].end_line == tokens[k].line):
                    above, j = tokens[k].line, k - 1
                    continue
            break
        self.sites.append(Site(path, line, kind, "\n".join(comments)))


def declared(root: pathlib.Path) -> Walker:
    """A walk of every module the shipping crates declare, under any cfg."""
    walker = Walker(root, gated=False)
    for crate in SHIPPING_CRATES:
        src = root / "crates" / crate / "src"
        walker.walk_file(src / "lib.rs", src)
    return walker


def kani_harnesses(walker: Walker) -> set[str]:
    """The Kani harnesses in the files the crates declare as modules, under any cfg."""
    pattern = re.compile(
        r"#\[kani::proof\][^\n]*\n(?:\s*#\[[^\n]*\n)*\s*(?:pub(?:\([^)]*\))?\s+)?fn\s+([A-Za-z0-9_]+)"
    )
    names = set()
    for path in set(walker.files):
        names.update(pattern.findall(path.read_text()))
    return names


def assembly_problems(walker: Walker) -> list[Site]:
    """Hand-written assembly: every `asm!`, `naked_asm!` or `global_asm!` outside the Lean
    routines, but for one `asm!` in the file of the system-call instruction (CLAUDE.md)."""
    problems, allowed = [], 0
    for path, line, macro in walker.assembly:
        relative = path.relative_to(walker.root).as_posix()
        if relative.startswith(LEAN_DIR + "/"):
            continue
        if relative == SYSTEM_CALL and macro == "asm" and allowed == 0:
            allowed += 1
            continue
        problems.append(Site(path, line, f"{macro}! written by hand", "", problem=True))
    return problems


def manifest_problems(root: pathlib.Path) -> list[Site]:
    """A shipping crate's manifest that turns on a feature of the allocator that never
    ships, in its dependency on it or, for the allocator, in its default or another
    feature that a serving build may have."""
    problems = []
    for crate in SHIPPING_CRATES:
        manifest = root / "crates" / crate / "Cargo.toml"
        if not manifest.is_file():
            continue
        data = tomllib.loads(manifest.read_text())
        tables = [data.get("dependencies", {})]
        tables += [t.get("dependencies", {}) for t in data.get("target", {}).values()]
        for table in tables:
            spec = table.get("cralloc")
            features = spec.get("features", []) if isinstance(spec, dict) else []
            for feature in features:
                if feature in NEVER_FEATURES:
                    problems.append(Site(manifest, 0, f"enables `{feature}` of cralloc", "", problem=True))
        if crate == "cralloc":
            for name, implied in data.get("features", {}).items():
                if name in NEVER_FEATURES:
                    continue
                for feature in implied:
                    if feature in NEVER_FEATURES:
                        problems.append(
                            Site(manifest, 0, f"feature `{name}` turns on `{feature}`", "", problem=True)
                        )
    return problems


def sites(root: pathlib.Path) -> tuple[list[Site], set[str]]:
    """Every `unsafe` site in the code that ships, every hand-written assembly and manifest
    that turns on a test feature as a problem, and the Kani harnesses that exist."""
    walker = Walker(root)
    for crate in SHIPPING_CRATES:
        src = root / "crates" / crate / "src"
        walker.walk_file(src / "lib.rs", src)
    everything = declared(root)
    found = walker.sites + assembly_problems(everything) + manifest_problems(root)
    return found, kani_harnesses(everything)


def verdict(site: Site, harnesses: set[str], defined) -> str | None:
    """What is wrong with a site, or `None`. `defined` holds the ledger's IDs."""
    if site.problem:
        return "not followed"
    if site.lean:
        return None
    if site.kind in CONTRACTS:
        return None if SAFETY_SECTION.search(site.justified) else "no '# Safety' section"
    if any(i in defined for i in ID.findall(site.justified)):
        return None
    if any(h in harnesses for h in KANI_NAMED.findall(site.justified)):
        return None
    return "cites no ledger entry or Kani harness"


