"""Finds the `unsafe` sites in the code that ships, for scripts/ledger-check.

The code that ships is what the allocator and preload crates compile in a build that serves a
program: the module tree from each crate's `src/lib.rs`, without what a `#[cfg(...)]` keeps
out of every such build (tests, Kani, Miri, the simulator's `sim` feature, `internals`), and
without a module whose own documentation says it is scaffolding with a line of the form
`//! Ledger: scaffolding, ...` (the twins, which serve tests only but compile everywhere).

A site is an `unsafe` block, `unsafe fn`, `unsafe impl`, `unsafe trait`, `unsafe extern`
block or `#[unsafe(...)]` attribute. Its justification is the comments directly above the line
it is on (across attributes, not across a blank line) and the comments on that line. It must
cite a ledger ID, or name a Kani harness as `Kani: \\`harness_name\\``, which must exist.

The scan is a small lexer and a token walk, not a Rust parser: enough for this crate's code.
"""

from __future__ import annotations

import itertools
import pathlib
import re
from dataclasses import dataclass

SHIPPING_CRATES = ("asmalloc", "asmalloc-preload")
LEAN_GENERATED = "// @generated by lean/Emit.lean."
SCAFFOLDING = re.compile(r"^//!\s*Ledger:\s*scaffolding\b", re.M)
KANI_NAMED = re.compile(r"Kani:\s*`(?:[A-Za-z0-9_]+::)*([A-Za-z0-9_]+)`")

# Features that a build serving a program may have, and those it never has.
# Sites that state a contract rather than discharge one: they need a `# Safety` section.
CONTRACTS = ("fn", "trait")

OPTIONAL_FEATURES = ("background", "allocator-api", "executable", "c-abi")


@dataclass
class Token:
    kind: str  # ident, punct, str, char, lifetime, num, comment
    text: str
    line: int


def lex(text: str) -> list[Token]:
    tokens: list[Token] = []
    i, line, n = 0, 1, len(text)

    def advance_to(j: int) -> None:
        nonlocal i, line
        line += text.count("\n", i, j)
        i = j

    while i < n:
        c = text[i]
        if c.isspace():
            advance_to(i + 1)
            continue
        start_line = line
        if text.startswith("//", i):
            j = text.find("\n", i)
            j = n if j < 0 else j
            tokens.append(Token("comment", text[i:j], start_line))
            advance_to(j)
            continue
        if text.startswith("/*", i):
            depth, j = 1, i + 2
            while j < n and depth:
                if text.startswith("/*", j):
                    depth, j = depth + 1, j + 2
                elif text.startswith("*/", j):
                    depth, j = depth - 1, j + 2
                else:
                    j += 1
            tokens.append(Token("comment", text[i:j], start_line))
            advance_to(j)
            continue
        if c.isalpha() or c == "_":
            j = i
            while j < n and (text[j].isalnum() or text[j] == "_"):
                j += 1
            word = text[i:j]
            if word in ("r", "br", "cr") and j < n and text[j] in "#\"":
                hashes = 0
                while j + hashes < n and text[j + hashes] == "#":
                    hashes += 1
                if j + hashes < n and text[j + hashes] == '"':
                    end = text.find('"' + "#" * hashes, j + hashes + 1)
                    end = n if end < 0 else end + 1 + hashes
                    tokens.append(Token("str", text[i:end], start_line))
                    advance_to(end)
                    continue
            if word in ("b", "c") and j < n and text[j] in "\"'":
                end = skip_quoted(text, j)
                tokens.append(Token("str", text[i:end], start_line))
                advance_to(end)
                continue
            tokens.append(Token("ident", word, start_line))
            advance_to(j)
            continue
        if c == '"':
            end = skip_quoted(text, i)
            tokens.append(Token("str", text[i:end], start_line))
            advance_to(end)
            continue
        if c == "'":
            if i + 1 < n and text[i + 1] == "\\":
                end = skip_quoted(text, i)
                tokens.append(Token("char", text[i:end], start_line))
                advance_to(end)
                continue
            if i + 2 < n and text[i + 2] == "'":
                tokens.append(Token("char", text[i : i + 3], start_line))
                advance_to(i + 3)
                continue
            j = i + 1
            while j < n and (text[j].isalnum() or text[j] == "_"):
                j += 1
            tokens.append(Token("lifetime", text[i:j], start_line))
            advance_to(j)
            continue
        if c.isdigit():
            j = i
            while j < n and (text[j].isalnum() or text[j] == "_"):
                j += 1
            tokens.append(Token("num", text[i:j], start_line))
            advance_to(j)
            continue
        tokens.append(Token("punct", c, start_line))
        advance_to(i + 1)
    return tokens


def skip_quoted(text: str, i: int) -> int:
    """The index just past the quoted literal that starts at `text[i]`."""
    quote, j, n = text[i], i + 1, len(text)
    while j < n and text[j] != quote:
        j += 2 if text[j] == "\\" else 1
    return j + 1


# The cfg predicates of a build that serves a program, each a dict of the options it has.
def shipping_configs() -> list[dict]:
    configs = []
    for env, *flags in itertools.product(("gnu", "musl"), *[(False, True)] * len(OPTIONAL_FEATURES)):
        features = {name for name, on in zip(OPTIONAL_FEATURES, flags) if on}
        configs.append({"target_env": env, "features": features})
    return configs


CONFIGS = shipping_configs()
FIXED = {
    "target_os": "linux",
    "target_arch": "x86_64",
    "target_family": "unix",
    "target_pointer_width": "64",
    "target_endian": "little",
}
TRUE_FLAGS = {"unix", "debug_assertions"}


def split_args(tokens: list[Token]) -> list[list[Token]]:
    """The comma-separated arguments of a parenthesized list's inside."""
    args, current, depth = [], [], 0
    for t in tokens:
        if t.kind == "punct" and t.text in "([{":
            depth += 1
        elif t.kind == "punct" and t.text in ")]}":
            depth -= 1
        if depth == 0 and t.kind == "punct" and t.text == ",":
            args.append(current)
            current = []
        else:
            current.append(t)
    if current:
        args.append(current)
    return args


def evaluate(pred: list[Token], config: dict) -> bool:
    if not pred:
        return False
    head = pred[0]
    if head.kind == "ident" and len(pred) > 1 and pred[1].text == "(":
        inner = split_args(pred[2:-1])
        results = [evaluate(arg, config) for arg in inner]
        if head.text == "all":
            return all(results)
        if head.text == "any":
            return any(results)
        if head.text == "not":
            return not results[0]
        return False
    if head.kind == "ident" and len(pred) == 3 and pred[1].text == "=":
        value = pred[2].text.strip('"')
        if head.text == "feature":
            return value in config["features"]
        if head.text == "target_env":
            return value == config["target_env"]
        return FIXED.get(head.text) == value
    if head.kind == "ident" and len(pred) == 1:
        return head.text in TRUE_FLAGS
    return False


def ships(pred: list[Token]) -> bool:
    return any(evaluate(pred, config) for config in CONFIGS)


def matching(tokens: list[Token], i: int) -> int:
    """The index of the bracket that closes the one at `tokens[i]`."""
    depth = 0
    for j in range(i, len(tokens)):
        t = tokens[j]
        if t.kind == "punct" and t.text in "([{":
            depth += 1
        elif t.kind == "punct" and t.text in ")]}":
            depth -= 1
            if depth == 0:
                return j
    return len(tokens) - 1


ITEM_WORDS = {
    "fn", "impl", "struct", "enum", "union", "trait", "mod", "macro_rules", "extern", "unsafe",
    "async", "const", "static", "use", "type", "let",
}
SEMICOLON_ITEMS = {"use", "static", "const", "type", "let"}


def item_end(tokens: list[Token], i: int) -> int:
    """The index of the last token of the item, field, arm or statement at `tokens[i]`."""
    j = i
    while j < len(tokens) and tokens[j].kind == "comment":
        j += 1
    k = j
    if k < len(tokens) and tokens[k].text == "pub":
        k += 1
        if k < len(tokens) and tokens[k].text == "(":
            k = matching(tokens, k) + 1
    first = tokens[k].text if k < len(tokens) else ""
    if first == "const" and k + 1 < len(tokens) and tokens[k + 1].text in ("fn", "unsafe"):
        first = "fn"
    item = first in ITEM_WORDS
    depth = 0
    for m in range(j, len(tokens)):
        t = tokens[m]
        if t.kind != "punct":
            continue
        if t.text in "([{":
            depth += 1
        elif t.text in ")]}":
            depth -= 1
            if depth < 0:
                return m - 1
            if depth == 0 and t.text == "}" and first not in SEMICOLON_ITEMS:
                nxt = tokens[m + 1] if m + 1 < len(tokens) else None
                if nxt is not None and nxt.kind == "punct" and nxt.text in ";,":
                    return m + 1
                return m
        elif depth == 0 and (t.text == ";" or (t.text == "," and not item)):
            return m
    return len(tokens) - 1


@dataclass
class Site:
    path: pathlib.Path
    line: int
    kind: str
    justified: str  # the comments that justify it
    lean: bool = False  # in a file the Lean emitter wrote from a proved artifact


def attribute_cfg(tokens: list[Token], i: int) -> tuple[int, list[Token] | None, bool]:
    """For an attribute starting at `tokens[i]` (`#`): the index of its `]`, the predicate if
    it is `cfg(...)`, and whether it is an inner attribute."""
    inner = tokens[i + 1].text == "!"
    open_at = i + 2 if inner else i + 1
    close = matching(tokens, open_at)
    body = tokens[open_at + 1 : close]
    if len(body) >= 3 and body[0].text == "cfg" and body[1].text == "(":
        return close, body[2:-1], inner
    return close, None, inner


class Walker:
    def __init__(self, harnesses: set[str]):
        self.harnesses = harnesses
        self.sites: list[Site] = []
        self.files: list[pathlib.Path] = []
        self.lean = False

    def walk_file(self, path: pathlib.Path, module_dir: pathlib.Path) -> None:
        text = path.read_text()
        if SCAFFOLDING.search(text):
            return
        self.files.append(path)
        tokens = lex(text)
        outer, self.lean = self.lean, text.startswith(LEAN_GENERATED)
        self.walk(tokens, 0, len(tokens), path, module_dir, text.splitlines())
        self.lean = outer

    def walk(self, tokens, start, end, path, module_dir, lines) -> None:
        i = start
        pending_path = None
        while i < end:
            t = tokens[i]
            if t.kind == "punct" and t.text == "#" and i + 1 < end and tokens[i + 1].text in "[!":
                close, pred, inner = attribute_cfg(tokens, i)
                if pred is not None and not ships(pred):
                    if inner:
                        return
                    after = close + 1
                    # Further attributes belong to the same item.
                    while after < end and tokens[after].text == "#":
                        after = attribute_cfg(tokens, after)[0] + 1
                    i = item_end(tokens, after) + 1
                    pending_path = None
                    continue
                body = tokens[(i + 2 if inner else i + 1) + 1 : close]
                if len(body) == 3 and body[0].text == "path" and body[1].text == "=":
                    pending_path = body[2].text.strip('"')
                if (
                    not inner
                    and body
                    and body[0].text == "unsafe"
                    and len(body) > 1
                    and body[1].text == "("
                ):
                    self.site(tokens, i, path, lines, "attribute")
                i = close + 1
                continue
            if t.kind == "ident" and t.text == "mod" and i + 2 < end and tokens[i + 1].kind == "ident":
                name, nxt = tokens[i + 1].text, tokens[i + 2]
                if nxt.text == ";":
                    self.declared(path, module_dir, name, pending_path)
                    pending_path = None
                    i += 3
                    continue
                if nxt.text == "{":
                    close = matching(tokens, i + 2)
                    self.walk(tokens, i + 3, close, path, module_dir / name, lines)
                    pending_path = None
                    i = close + 1
                    continue
            if t.kind == "ident" and t.text == "unsafe":
                kind = self.kind(tokens, i)
                # A method of a trait's implementation states no contract of its own: it has
                # the trait's, which is documented where the trait is.
                if kind and not (kind == "fn" and in_trait_impl(tokens, i)):
                    self.site(tokens, i, path, lines, kind)
            if t.kind == "punct" and t.text in ";{}":
                pending_path = None
            i += 1

    def declared(self, path, module_dir, name, explicit) -> None:
        if explicit is not None:
            # `#[path]` is relative to the declaring file's directory for a crate root or mod.rs.
            target = path.parent / explicit
            child_dir = target.parent / target.stem
        else:
            target = module_dir / f"{name}.rs"
            child_dir = module_dir / name
            if not target.exists():
                target = module_dir / name / "mod.rs"
        if target.exists():
            if target.name == "mod.rs":
                child_dir = target.parent
            self.walk_file(target, child_dir)

    @staticmethod
    def kind(tokens, i) -> str | None:
        nxt = tokens[i + 1] if i + 1 < len(tokens) else None
        if nxt is None:
            return None
        if nxt.text == "{":
            return "block"
        if nxt.text in ("impl", "trait"):
            return nxt.text
        j = i + 1
        if nxt.text == "extern":
            j += 1
            if j < len(tokens) and tokens[j].kind == "str":
                j += 1
            if j < len(tokens) and tokens[j].text == "{":
                return "extern block"
        if j < len(tokens) and tokens[j].text == "fn":
            # `unsafe fn(...)` is a function pointer type, not a function.
            if j + 1 < len(tokens) and tokens[j + 1].kind == "ident":
                return "fn"
        return None

    def site(self, tokens, i, path, lines, kind) -> None:
        line = tokens[i].line
        if self.lean:
            self.sites.append(Site(path, line, kind, "", lean=True))
            return
        comments = [t.text for t in tokens if t.kind == "comment" and t.line == line]
        # Back to the end of the previous statement or item: the comments above the statement
        # the site is in, including an item's documentation over its attributes, and those
        # inside it before the site.
        # A parenthesized or bracketed group before the site, such as a pattern
        # `Some(Kind { .. })`, is passed over whole.
        k = i - 1
        while k >= 0 and not (tokens[k].kind == "punct" and tokens[k].text in ";{}"):
            if tokens[k].kind == "comment":
                comments.append(tokens[k].text)
            elif tokens[k].kind == "punct" and tokens[k].text in ")]":
                k = opening(tokens, k)
            k -= 1
        self.sites.append(Site(path, line, kind, "\n".join(comments)))


def opening(tokens: list[Token], close: int) -> int:
    """The index of the bracket that opens the one at `tokens[close]`."""
    depth = 0
    for j in range(close, -1, -1):
        t = tokens[j]
        if t.kind == "punct" and t.text in ")]}":
            depth += 1
        elif t.kind == "punct" and t.text in "([{":
            depth -= 1
            if depth == 0:
                return j
    return 0


def in_trait_impl(tokens: list[Token], i: int) -> bool:
    """Whether `tokens[i]` is directly inside an `impl Trait for Type { ... }` block."""
    depth = 0
    for j in range(i - 1, -1, -1):
        t = tokens[j]
        if t.kind != "punct":
            continue
        if t.text in ")]}":
            depth += 1
        elif t.text in "([{":
            if depth:
                depth -= 1
                continue
            if t.text != "{":
                return False
            header = []
            for k in range(j - 1, -1, -1):
                if tokens[k].kind == "punct" and tokens[k].text in ";{}":
                    break
                header.append(tokens[k].text)
            return "impl" in header and "for" in header
    return False


def kani_harnesses(root: pathlib.Path) -> set[str]:
    names = set()
    pattern = re.compile(r"#\[kani::proof\][^\n]*\n(?:\s*#\[[^\n]*\n)*\s*(?:pub(?:\([^)]*\))?\s+)?fn\s+([A-Za-z0-9_]+)")
    for path in root.rglob("*.rs"):
        if "target" in path.parts:
            continue
        names.update(pattern.findall(path.read_text()))
    return names


def sites(root: pathlib.Path) -> tuple[list[Site], set[str]]:
    """Every `unsafe` site in the code that ships, and the Kani harnesses that exist."""
    harnesses = kani_harnesses(root / "crates")
    walker = Walker(harnesses)
    for crate in SHIPPING_CRATES:
        src = root / "crates" / crate / "src"
        walker.walk_file(src / "lib.rs", src)
    return walker.sites, harnesses
