def self_test() -> list[str]:
    """The cases above; the names of those that came out wrong."""
    failures = []
    with tempfile.TemporaryDirectory() as d:
        for n, (name, files, expected) in enumerate(CASES):
            root = pathlib.Path(d) / str(n)
            for crate in SHIPPING_CRATES:
                (root / "crates" / crate / "src").mkdir(parents=True)
                (root / "crates" / crate / "src" / "lib.rs").write_text("")
            for rel, text in files.items():
                p = root / "crates" / "cralloc" / "src" / rel
                p.parent.mkdir(parents=True, exist_ok=True)
                p.write_text(text)
            found, harnesses = sites(root)
            wrong = [s for s in found if verdict(s, harnesses, {"FOO-01"}) is not None]
            if len(wrong) != expected:
                failures.append(f"{name}: {len(wrong)} wrong, expected {expected}")
    return failures


